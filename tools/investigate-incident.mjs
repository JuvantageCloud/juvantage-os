#!/usr/bin/env node
/**
 * Offline / CI investigator for OpsIncident payloads.
 * Writes a reviewable markdown proposal — never merges.
 *
 * Usage:
 *   node tools/investigate-incident.mjs --input incident.json --out .ci/incident-proposal.md
 *   echo '{"message":"..."}' | node tools/investigate-incident.mjs --out .ci/incident-proposal.md
 */
import { createHash } from "node:crypto";
import { mkdir, readFile, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";

function arg(name, fallback = null) {
  const i = process.argv.indexOf(name);
  if (i === -1) return fallback;
  return process.argv[i + 1] ?? fallback;
}

function normalizePath(path = "") {
  return path
    .split("?")[0]
    .replace(/\/[0-9a-f]{8,}/gi, "/:id")
    .replace(/\/\d+/g, "/:id");
}

function suggestFix(incident) {
  const msg = String(incident.message || "").toLowerCase();
  const path = incident.path || "";
  const suggestions = [];
  let likelyFile = "apps/api/src/index.ts";
  let title = `Investigate: ${String(incident.message || "server failure").slice(0, 72)}`;

  if (msg.includes("unauthorized") || incident.statusCode === 401) {
    likelyFile = "apps/api/src/middleware/auth.ts";
    suggestions.push("Align JWT_SECRET across envs; verify Bearer token on Desktop.");
    title = "Fix auth 401 on OS Brain request";
  } else if (msg.includes("google") || path.includes("oauth")) {
    likelyFile = "apps/api/src/services/osConnectors.ts";
    suggestions.push("Check Google OAuth env + redirect URI; keep demo connect working.");
    title = "Fix Google OAuth / connector failure";
  } else if (msg.includes("prisma") || msg.includes("database") || msg.includes("sqlite")) {
    likelyFile = "apps/api/prisma/schema.prisma";
    suggestions.push("prisma generate/db push; verify DATABASE_URL per environment.");
    title = "Fix database / Prisma incident";
  } else if (path.includes("/os/loops") || msg.includes("loop")) {
    likelyFile = "apps/api/src/services/osLoops.ts";
    suggestions.push("Reproduce demo connect → extract; add regression test for classifier/route.");
    title = "Fix OS loops failure";
  } else if (incident.source === "desktop") {
    likelyFile = "apps/desktop/src/lib/api.ts";
    suggestions.push("Verify VITE_API_BASE_URL; improve client error reporting/retry.");
    title = "Fix Desktop → Brain client failure";
  } else {
    suggestions.push("Add a failing regression test that reproduces this message.");
    suggestions.push("Harden the route; do not leak stacks to clients in prod.");
  }

  if (incident.stack) {
    const hit = String(incident.stack).match(/apps\/[^\s):]+|src\/[^\s):]+/);
    if (hit) likelyFile = hit[0];
  }

  return {
    title,
    likelyFile,
    suggestions,
    proposedChecks: [
      "npm test -w @juvantage/api",
      "npm run build -w @juvantage/api",
      "npx tsc -p apps/desktop --noEmit",
    ],
    policy:
      "Juvantage OS capability: propose → human approve. Never auto-merge or auto-deploy.",
  };
}

async function readInput() {
  const inputPath = arg("--input");
  if (inputPath) {
    return JSON.parse(await readFile(resolve(inputPath), "utf8"));
  }
  if (!process.stdin.isTTY) {
    const chunks = [];
    for await (const chunk of process.stdin) chunks.push(chunk);
    const raw = Buffer.concat(chunks).toString("utf8").trim();
    if (raw) return JSON.parse(raw);
  }
  return {
    message: "Example incident — no input provided",
    path: "/os/health-check",
    method: "GET",
    statusCode: 500,
    source: "ci",
  };
}

function renderMarkdown(incident, suggestion) {
  const fp = createHash("sha256")
    .update(
      [
        incident.source || "api",
        incident.method || "",
        normalizePath(incident.path || ""),
        String(incident.message || "").slice(0, 240),
        String(incident.statusCode || 500),
      ].join("|"),
    )
    .digest("hex")
    .slice(0, 32);

  return `# ${suggestion.title}

> Auto-generated by \`tools/investigate-incident.mjs\` for **review only**.
> This is a **Juvantage OS** capability: catch failure → investigate → **suggest change** → human approves.

## Incident

| Field | Value |
|-------|-------|
| Fingerprint | \`${incident.fingerprint || fp}\` |
| Source | ${incident.source || "api"} |
| Method | ${incident.method || "—"} |
| Path | \`${normalizePath(incident.path || "") || "—"}\` |
| Status | ${incident.statusCode ?? "—"} |
| Occurrences | ${incident.occurrenceCount ?? 1} |

### Message

\`\`\`
${incident.message || "(none)"}
\`\`\`

### Stack (truncated)

\`\`\`
${(incident.stack || "").slice(0, 2500) || "(none)"}
\`\`\`

## Suggested change (for review)

- **Likely file:** \`${suggestion.likelyFile}\`
- **Policy:** ${suggestion.policy}

### Recommendations

${suggestion.suggestions.map((s) => `- ${s}`).join("\n")}

### Verification before merge

\`\`\`bash
${suggestion.proposedChecks.join("\n")}
\`\`\`

## Next human steps

1. Open the likely file and confirm root cause.
2. Implement the smallest fix + a regression test.
3. Open / update this PR — **do not** enable auto-merge.
4. After deploy, mark the OpsIncident \`resolved\` on the Brain.
`;
}

const incident = await readInput();
const suggestion = incident.suggestion || suggestFix(incident);
const out =
  arg("--out") ||
  resolve(".ci/incident-proposal.md");
await mkdir(dirname(out), { recursive: true });
const md = renderMarkdown(incident, suggestion);
await writeFile(out, md, "utf8");
const metaOut = out.replace(/\.md$/, ".json");
await writeFile(
  metaOut,
  JSON.stringify({ incident, suggestion, generatedAt: new Date().toISOString() }, null, 2),
  "utf8",
);
console.log(`Wrote ${out}`);
console.log(`Wrote ${metaOut}`);
